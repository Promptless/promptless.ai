/**
 * Render the MCP tools reference partials from the exported MCP catalog.
 *
 * Input: `src/data/mcp/catalog.json`, written by `export-catalog.py` from the
 * tool, skill, and resource definitions in Promptless/promptless.
 * Output: MDX partials under `src/partials/generated/mcp/`, which
 * `src/content/docs/docs/for-docs/reference/mcp-tools.mdx` embeds:
 *
 * - `tools/<tool_name>.mdx`: one tool's description, annotation, arguments,
 *   and result fields. The page keeps each `### <tool_name>` heading, because
 *   the product links to those anchors and Astro leaves headings in an
 *   imported file out of the table of contents (ADR 0007).
 *
 * - `skills.mdx`: each skill's description.
 *
 * It also refreshes the tables between `{/* generated:begin <name> *\/}` and
 * `{/* generated:end <name> *\/}` comments on the page: the tool table that
 * starts each tool group, and the skills table. Those stay on the page because
 * `manni lint structure` counts only a page's own tables.
 *
 * Usage:
 *   npm run generate:mcp-reference           # write the partials
 *   npm run check:mcp-reference              # fail if partials or page headings are stale
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

type Schema = {
  type?: string | string[];
  description?: string;
  enum?: unknown[];
  default?: unknown;
  items?: Schema;
  properties?: Record<string, Schema>;
  required?: string[];
  anyOf?: Schema[];
  oneOf?: Schema[];
  $ref?: string;
  $defs?: Record<string, Schema>;
  [key: string]: unknown;
};

type Tool = {
  name: string;
  title?: string;
  description?: string;
  inputSchema: Schema;
  outputSchema?: Schema;
  annotations?: { readOnlyHint?: boolean; destructiveHint?: boolean };
  'x-promptless-members-only': boolean;
};

type Skill = { uri: string; frontmatter: { name: string; description: string } };

type Catalog = {
  source: { repository: string; commit: string | null };
  surfaces: { key: string; path: string; name: string; tools: string[]; skills: string[]; resources: string[] }[];
  tools: Tool[];
  skills: Skill[];
  resources: { uri: string; name: string; mimeType?: string }[];
};

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const CATALOG = path.join(ROOT, 'src', 'data', 'mcp', 'catalog.json');
const OUT_DIR = path.join(ROOT, 'src', 'partials', 'generated', 'mcp');
const PAGE = path.join(ROOT, 'src', 'content', 'docs', 'docs', 'for-docs', 'reference', 'mcp-tools.mdx');
const PARTIAL_SPECIFIER = '@partials/generated/mcp';
/** Deepest dotted path rendered in an argument or result table, such as `messages[].author.type`. */
const MAX_FIELD_DEPTH = 3;

const catalog: Catalog = JSON.parse(readFileSync(CATALOG, 'utf8'));
const header = (what: string) =>
  `{/* Generated by scripts/mcp-reference/generate.ts from src/data/mcp/catalog.json (${catalog.source.repository}@${(catalog.source.commit ?? 'unknown').slice(0, 12)}): ${what}. Don't edit by hand. Run npm run generate:mcp-reference. */}\n`;

// ---------------------------------------------------------------------------
// Text

/** snake_case names the catalog defines; prose mentions of them render as code. */
const identifiers = new Set<string>();
function collectIdentifiers(schema: Schema | undefined): void {
  if (!schema || typeof schema !== 'object') return;
  for (const [name, child] of Object.entries(schema.properties ?? {})) {
    if (name.includes('_')) identifiers.add(name);
    collectIdentifiers(child);
  }
  collectIdentifiers(schema.items);
  for (const child of [...(schema.anyOf ?? []), ...(schema.oneOf ?? []), ...Object.values(schema.$defs ?? {})]) {
    collectIdentifiers(child);
  }
}
for (const tool of catalog.tools) {
  identifiers.add(tool.name);
  collectIdentifiers(tool.inputSchema);
  collectIdentifiers(tool.outputSchema);
}
const skillNames = new Set(catalog.skills.map((skill) => skill.frontmatter.name));

/** Escape text for MDX, and render known identifiers and URIs as code. */
function prose(text: string, { inTable = false } = {}): string {
  const parts = text.split(/(skill:\/\/\S+[^\s.,;:)]|\b[a-z][a-z0-9]*(?:[_-][a-z0-9]+)+\b)/g);
  return parts
    .map((part, index) => {
      const isToken = index % 2 === 1;
      if (isToken && (part.startsWith('skill://') || identifiers.has(part) || skillNames.has(part))) return `\`${part}\``;
      let escaped = part
        .replace(/\\/g, '\\\\')
        .replace(/[*[\]{}]/g, (char) => `\\${char}`)
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;');
      if (inTable) escaped = escaped.replace(/\|/g, '\\|');
      return escaped;
    })
    .join('')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Drop the trailing link back to these docs that every tool description ends with. */
function toolDescription(tool: Tool): string {
  return (tool.description ?? '').replace(/\s*Documentation: https?:\/\/\S+\s*$/, '').trim();
}

const code = (value: unknown) => `\`${typeof value === 'string' ? value : JSON.stringify(value)}\``;

function sentenceList(items: string[]): string {
  if (items.length <= 2) return items.join(' or ');
  return `${items.slice(0, -1).join(', ')}, or ${items.at(-1)}`;
}

// ---------------------------------------------------------------------------
// Schemas

function resolve(schema: Schema, defs: Record<string, Schema>): Schema {
  if (!schema.$ref) return schema;
  const name = schema.$ref.replace(/^#\/\$defs\//, '');
  const target = defs[name];
  if (!target) throw new Error(`Unresolved schema reference ${schema.$ref}`);
  // A $ref's sibling keywords (such as description) apply alongside the target.
  const { $ref: _ref, ...siblings } = schema;
  return { ...resolve(target, defs), ...siblings };
}

function typeName(input: Schema, defs: Record<string, Schema>): string {
  const schema = resolve(input, defs);
  const variants = schema.anyOf ?? schema.oneOf;
  if (variants) {
    return [...new Set(variants.map((variant) => typeName(variant, defs)))].join(' or ');
  }
  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
  if (types.length === 0) return schema.enum ? 'string' : 'any';
  return types
    .map((type) => (type === 'array' && schema.items ? `array of ${typeName(schema.items, defs)}` : type))
    .join(' or ');
}

const LIMITS: [keyof Schema, string][] = [
  ['minimum', 'Minimum'],
  ['maximum', 'Maximum'],
  ['minLength', 'Minimum length'],
  ['maxLength', 'Maximum length'],
  ['minItems', 'Minimum entries'],
  ['maxItems', 'Maximum entries'],
];

/** Describe one field. Defaults and limits are rendered for arguments, which a caller chooses. */
function fieldDescription(input: Schema, defs: Record<string, Schema>, isArgument: boolean): string {
  const schema = resolve(input, defs);
  const notes: string[] = [];
  if (schema.description) notes.push(prose(schema.description, { inTable: true }));
  const values = (schema.enum ?? []).filter((value) => value !== null);
  if (values.length > 0) notes.push(`One of ${sentenceList(values.map(code))}.`);
  if (isArgument) {
    const limits = LIMITS.filter(([key]) => typeof schema[key] === 'number').map(
      ([key, label]) => `${label}: ${(schema[key] as number).toLocaleString('en-US')}`,
    );
    if (limits.length > 0) notes.push(`${limits.join('. ')}.`);
    if (schema.default !== undefined) notes.push(`Defaults to ${code(schema.default)}.`);
  }
  return notes.join(' ');
}

type Row = { name: string; type: string; required: boolean; description: string };

/** Flatten an object schema's fields into rows, descending into objects and arrays of objects. */
function rows(input: Schema, defs: Record<string, Schema>, isArgument: boolean, prefix = '', depth = 1): Row[] {
  const schema = resolve(input, defs);
  const required = new Set(schema.required ?? []);
  const result: Row[] = [];
  for (const [name, child] of Object.entries(schema.properties ?? {})) {
    const fieldName = `${prefix}${name}`;
    result.push({
      name: fieldName,
      type: typeName(child, defs),
      required: required.has(name),
      description: fieldDescription(child, defs, isArgument),
    });
    if (depth >= MAX_FIELD_DEPTH) continue;
    const resolved = resolve(child, defs);
    const objectVariant = [resolved, ...(resolved.anyOf ?? [])].map((variant) => resolve(variant, defs)).find((v) => v.properties);
    if (objectVariant) result.push(...rows(objectVariant, defs, isArgument, `${fieldName}.`, depth + 1));
    const items = resolved.items ? resolve(resolved.items, defs) : undefined;
    if (items?.properties) result.push(...rows(items, defs, isArgument, `${fieldName}[].`, depth + 1));
  }
  return result;
}

/** A GFM table, padded the way `npm run lint:md:fix` (remark-stringify) pads one, so the autofix leaves it alone. */
function table(headers: string[], body: string[][]): string {
  const all = [headers, ...body];
  const widths = headers.map((_header, column) => Math.max(3, ...all.map((row) => [...row[column]].length)));
  const line = (row: string[]) => `| ${row.map((cell, column) => cell + ' '.repeat(widths[column] - [...cell].length)).join(' | ')} |`;
  return [line(headers), `| ${widths.map((width) => '-'.repeat(width)).join(' | ')} |`, ...body.map(line)].join('\n');
}

// ---------------------------------------------------------------------------
// Partials

function annotation(tool: Tool): string {
  if (tool.annotations?.readOnlyHint) return 'Read-only';
  if (tool.annotations?.destructiveHint) return 'Changes existing content';
  return 'Changes data';
}

function toolPartial(tool: Tool): string {
  const surfaces = catalog.surfaces.filter((surface) => surface.tools.includes(tool.name));
  const facts = [
    `- **Annotation:** ${annotation(tool)}`,
    `- **Server paths:** ${surfaces.map((surface) => code(surface.path)).join(', ')}`,
  ];
  if (!tool['x-promptless-members-only']) {
    facts.push('- **Unclaimed organizations:** Available before a person claims an organization an agent created.');
  }

  const sections = [header(tool.name), `${prose(toolDescription(tool))}\n`, `${facts.join('\n')}\n`];

  const inputDefs = tool.inputSchema.$defs ?? {};
  const inputRows = rows(tool.inputSchema, inputDefs, true);
  if (inputRows.length === 0) {
    sections.push('It takes no arguments.\n');
  } else {
    sections.push(
      `**Arguments**\n\n${table(
        ['Argument', 'Type', 'Required', 'Description'],
        inputRows.map((row) => [code(row.name), row.type, row.required ? 'Yes' : 'No', row.description]),
      )}\n`,
    );
  }

  if (tool.outputSchema) {
    const outputRows = rows(tool.outputSchema, tool.outputSchema.$defs ?? {}, false);
    if (outputRows.length > 0) {
      sections.push(
        `**Result**\n\n${table(
          ['Field', 'Type', 'Description'],
          outputRows.map((row) => [code(row.name), row.type, row.description]),
        )}\n`,
      );
    }
  }
  return sections.join('\n');
}

function groupKey(toolName: string): string {
  const keys = catalog.surfaces.filter((surface) => surface.tools.includes(toolName)).map((surface) => surface.key);
  return keys.length === catalog.surfaces.length ? 'every-surface' : `only-on-${keys.join('-and-')}`;
}

/** Tables written into the page itself, because `manni lint structure` counts only tables on the page. */
function regions(): Map<string, string> {
  const groups = new Map<string, Tool[]>();
  for (const tool of catalog.tools) {
    const key = groupKey(tool.name);
    groups.set(key, [...(groups.get(key) ?? []), tool]);
  }
  const result = new Map<string, string>();
  for (const [key, tools] of groups) {
    result.set(
      `tools-${key.replace(/^every-surface$/, 'on-every-surface')}`,
      table(
        ['Tool', 'Annotation'],
        tools.map((tool) => [`[${code(tool.name)}](#${tool.name})`, annotation(tool)]),
      ),
    );
  }
  const skillRows = catalog.skills.map((skill) => {
    const paths = catalog.surfaces.filter((surface) => surface.skills.includes(skill.uri)).map((surface) => code(surface.path));
    const resources = catalog.resources
      .filter((resource) => resource.uri.startsWith(skill.uri.replace(/SKILL\.md$/, '')))
      .map((resource) => code(resource.uri));
    return [code(skill.frontmatter.name), resources.join(', '), paths.join(', ')];
  });
  result.set('skills', table(['Skill', 'Resources', 'Server paths'], skillRows));
  return result;
}

/** Each skill's own description. Text written in the source stays in partials, and the page carries only tables of names. */
function skillsPartial(): string {
  const items = catalog.skills.map((skill) => `- ${code(skill.frontmatter.name)}: ${prose(skill.frontmatter.description)}`);
  return `${header('skills')}\n${items.join('\n')}\n`;
}

function render(): Map<string, string> {
  const files = new Map<string, string>();
  for (const tool of catalog.tools) files.set(`tools/${tool.name}.mdx`, toolPartial(tool));
  files.set('skills.mdx', skillsPartial());
  return files;
}

// ---------------------------------------------------------------------------
// Page regions: {/* generated:begin <name> ... */} ... {/* generated:end <name> */}

const regionPattern = (name: string) =>
  new RegExp(`(\\{/\\* generated:begin ${name}\\b[^\\n]*\\*/\\}\\n)([\\s\\S]*?)(\\{/\\* generated:end ${name} \\*/\\})`);

/** Return the page with every generated region refreshed, and the regions it lacks. */
function withRegions(page: string): { page: string; missing: string[]; unknown: string[] } {
  const missing: string[] = [];
  let updated = page;
  const expected = regions();
  for (const [name, content] of expected) {
    const pattern = regionPattern(name);
    if (!pattern.test(updated)) {
      missing.push(name);
      continue;
    }
    updated = updated.replace(pattern, (_match, begin: string, _old: string, end: string) => `${begin}\n${content}\n\n${end}`);
  }
  const unknown = [...page.matchAll(/\{\/\* generated:begin ([\w-]+)/g)].map((match) => match[1]).filter((name) => !expected.has(name));
  return { page: updated, missing, unknown };
}

// ---------------------------------------------------------------------------
// Page check

export const componentName = (toolName: string) =>
  `${toolName.replace(/(^|_)([a-z0-9])/g, (_match, _sep, char: string) => char.toUpperCase())}Tool`;

/** Report how the reference page disagrees with the catalog: headings, imports, and embeds. */
function pageProblems(files: Map<string, string>): string[] {
  const page = readFileSync(PAGE, 'utf8');
  const problems: string[] = [];
  const refreshed = withRegions(page);
  for (const name of refreshed.missing) problems.push(`page has no generated:begin ${name} region`);
  for (const name of refreshed.unknown) problems.push(`page has a generated:begin ${name} region the catalog no longer generates`);
  const imports = new Map<string, string>();
  for (const match of page.matchAll(/^import\s+([A-Z]\w*)\s+from\s+['"]([^'"]+)['"];?\s*$/gm)) imports.set(match[2], match[1]);

  for (const file of files.keys()) {
    if (!imports.has(`${PARTIAL_SPECIFIER}/${file}`)) problems.push(`page doesn't import ${PARTIAL_SPECIFIER}/${file}`);
  }
  for (const specifier of imports.keys()) {
    if (specifier.startsWith(`${PARTIAL_SPECIFIER}/`) && !files.has(specifier.slice(PARTIAL_SPECIFIER.length + 1))) {
      problems.push(`page imports ${specifier}, which the catalog no longer generates`);
    }
  }

  const sections = page.split(/^(?=#{2,3} )/m);
  const toolHeadings = new Set<string>();
  for (const section of sections) {
    const heading = section.match(/^### `([a-z0-9_]+)`\s*$/m);
    if (!heading) continue;
    const name = heading[1];
    toolHeadings.add(name);
    const component = imports.get(`${PARTIAL_SPECIFIER}/tools/${name}.mdx`);
    if (!catalog.tools.some((tool) => tool.name === name)) {
      problems.push(`page has a ### \`${name}\` heading, but no MCP surface lists that tool`);
    } else if (!component || !new RegExp(`<${component}\\s*/>`).test(section)) {
      problems.push(`the ### \`${name}\` section doesn't embed its generated partial`);
    }
  }
  for (const tool of catalog.tools) {
    if (!toolHeadings.has(tool.name)) problems.push(`page has no ### \`${tool.name}\` heading`);
  }
  return problems;
}

// ---------------------------------------------------------------------------

function main(): void {
  const check = process.argv.includes('--check');
  const files = render();

  if (check) {
    const problems: string[] = [];
    const existing = new Set<string>();
    const walk = (dir: string, prefix = '') => {
      for (const entry of readdirSync(dir, { withFileTypes: true })) {
        if (entry.isDirectory()) walk(path.join(dir, entry.name), `${prefix}${entry.name}/`);
        else existing.add(`${prefix}${entry.name}`);
      }
    };
    try {
      walk(OUT_DIR);
    } catch {
      // A missing directory reports every file as missing below.
    }
    for (const [file, content] of files) {
      let current: string | undefined;
      try {
        current = readFileSync(path.join(OUT_DIR, file), 'utf8');
      } catch {
        current = undefined;
      }
      if (current !== content) problems.push(`${file} is ${current === undefined ? 'missing' : 'stale'}`);
    }
    for (const file of existing) if (!files.has(file)) problems.push(`${file} is no longer generated`);
    const page = readFileSync(PAGE, 'utf8');
    if (withRegions(page).page !== page) problems.push(`a generated table in ${path.relative(ROOT, PAGE)} is stale`);
    problems.push(...pageProblems(files));
    if (problems.length > 0) {
      console.error(`MCP tools reference is out of date:\n- ${problems.join('\n- ')}\nRun npm run generate:mcp-reference and update ${path.relative(ROOT, PAGE)}.`);
      process.exit(1);
    }
    console.log(`MCP tools reference matches ${path.relative(ROOT, CATALOG)}.`);
    return;
  }

  rmSync(OUT_DIR, { recursive: true, force: true });
  for (const [file, content] of files) {
    mkdirSync(path.dirname(path.join(OUT_DIR, file)), { recursive: true });
    writeFileSync(path.join(OUT_DIR, file), content);
  }
  console.log(`Wrote ${files.size} partials to ${path.relative(ROOT, OUT_DIR)}.`);
  const page = readFileSync(PAGE, 'utf8');
  const refreshed = withRegions(page).page;
  if (refreshed !== page) {
    writeFileSync(PAGE, refreshed);
    console.log(`Updated the generated tables in ${path.relative(ROOT, PAGE)}.`);
  }
  const problems = pageProblems(files);
  if (problems.length > 0) console.warn(`Update ${path.relative(ROOT, PAGE)}:\n- ${problems.join('\n- ')}`);
}

main();
